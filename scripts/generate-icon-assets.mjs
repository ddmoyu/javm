import { mkdir, writeFile } from "node:fs/promises";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { CaretDownIcon } from "@phosphor-icons/react/dist/csr/CaretDown";

// 为没有图标插槽的 Mantine 控件导出官方 Phosphor 图形，不维护手写 SVG 路径。
const directory = new URL("../resources/icons/", import.meta.url);
await mkdir(directory, { recursive: true });
const svg = renderToStaticMarkup(createElement(CaretDownIcon, { size: 256, weight: "regular" }));
await writeFile(
  new URL("caret-down.svg", directory),
  `<!-- Generated by pnpm icons:generate from @phosphor-icons/react (MIT). -->\n${svg}\n`,
);
